    def test_04_recycling_pathway_mapping_logic(self):
        """[LOCAL LOGIC] Verifies safe circular pathway assignment and pending_review on low confidence."""
        # Recyclable categories with high confidence -> recycling
        self.assertEqual(supabase_client.determine_processing_pathway("plastic", 0.95), "recycling")
        self.assertEqual(supabase_client.determine_processing_pathway("cardboard", 0.80), "recycling")
        self.assertEqual(supabase_client.determine_processing_pathway("glass", 0.90), "recycling")
        self.assertEqual(supabase_client.determine_processing_pathway("metal", 0.85), "recycling")
        self.assertEqual(supabase_client.determine_processing_pathway("paper", 0.75), "recycling")

        # Residual trash -> landfill
        self.assertEqual(supabase_client.determine_processing_pathway("trash", 0.90), "landfill")

        # Low confidence (< 0.65) -> pending_review (prevents unsafe automatic processing)
        self.assertEqual(supabase_client.determine_processing_pathway("plastic", 0.50), "pending_review")
        self.assertEqual(supabase_client.determine_processing_pathway("glass", 0.64), "pending_review")
        self.assertEqual(supabase_client.determine_processing_pathway("trash", 0.40, needs_manual_review=True), "pending_review")

        print("\n[TEST 4 PASSED] Circular pathway safety logic verified (low confidence held for pending_review).")

