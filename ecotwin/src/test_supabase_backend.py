    def test_08_end_to_end_camera_classify_and_supabase_persistence(self):
        """[REAL SUPABASE CLOUD & CNN] Live camera capture -> CNN inference -> PostgreSQL classification + operation stored."""
        data = {
            "live_frame": (io.BytesIO(self.test_jpeg_bytes), "live_camera_capture.jpg", "image/jpeg"),
            "capture_source": "live_camera",
        }
        resp = self.client.post(
            "/api/classify",
            data=data,
            content_type="multipart/form-data",
            headers={"X-Capture-Source": "live_camera"}
        )
        self.assertEqual(resp.status_code, 200)
        res = resp.get_json()
        self.assertTrue(res["success"])
        self.assertIn("classification_id", res["data"])
        self.assertIn("operation_id", res["data"])
        self.assertIn("processing_pathway", res["data"])
        self.assertIn("database_status", res["data"])

        # Track for cleanup
        cls_id = res["data"]["classification_id"]
        self.tracked_classification_ids.append(cls_id)

        # Verify classification was stored in live database view
        views = supabase_client.fetch_dashboard_views()
        matching = [r for r in views["recent_classifications"] if r.get("classification_id") == cls_id]
        self.assertGreater(len(matching), 0, "Classification must be found in view_recent_classifications")
        print(f"\n[TEST 8 PASSED] End-to-end live camera classification successfully persisted: {cls_id}")

