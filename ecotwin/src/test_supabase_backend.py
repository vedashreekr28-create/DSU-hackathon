        self.assertIn("confidence NUMERIC(5, 4)", sql_content)
        self.assertIn("processing_pathway TEXT NOT NULL", sql_content)
        self.assertIn("'pending_review'", sql_content)
        self.assertIn("is_simulated", sql_content)

        # Check RLS Policies
        self.assertIn("ALTER TABLE waste_classifications ENABLE ROW LEVEL SECURITY", sql_content)
        self.assertIn("ALTER TABLE recycling_operations ENABLE ROW LEVEL SECURITY", sql_content)
        self.assertIn("ALTER TABLE recycling_bins ENABLE ROW LEVEL SECURITY", sql_content)
        self.assertIn("TO service_role", sql_content)

        # Check Views
        self.assertIn("view_total_classifications", sql_content)
        self.assertIn("view_category_distribution", sql_content)
        self.assertIn("view_recent_classifications", sql_content)
        self.assertIn("view_pathway_summary", sql_content)
        self.assertIn("view_operations_status", sql_content)
        self.assertIn("view_bin_utilization", sql_content)

        print("\n[TEST 1 PASSED] 001_initial_schema.sql verified with complete tables, constraints, RLS, and views.")

