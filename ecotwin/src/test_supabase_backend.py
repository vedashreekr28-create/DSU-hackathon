    def test_10_cloud_direct_supabase_crud_lifecycle_and_cleanup(self):
        """[REAL SUPABASE CLOUD DIRECT] Verifies direct Cloud PostgreSQL insert, read, foreign-key, view, and deletion."""
        self.assertTrue(supabase_client.is_supabase_active(), "Supabase must be active for direct cloud test")
        client = supabase_client.get_supabase_client()
        self.assertIsNotNone(client)

        unique_test_id = str(uuid.uuid4())
        self.tracked_classification_ids.append(unique_test_id)

        try:
            # 1. Insert temporary test classification directly into Cloud Supabase
            inserted = supabase_client.record_waste_classification(
                waste_category="glass",
                confidence=0.9750,
                model_version=config.MODEL_VERSION,
                capture_source="live_camera",
                classification_status="successful",
                metadata={"test_run": "automated_backend_verification", "scope": "direct_cloud_test"},
                classification_id=unique_test_id
            )
            self.assertEqual(inserted["id"], unique_test_id)

            # 2. Direct cloud SELECT verification
            fetch_res = client.table("waste_classifications").select("*").eq("id", unique_test_id).execute()
            self.assertEqual(len(fetch_res.data), 1, "Inserted test record must exist in cloud table")
            row = fetch_res.data[0]
            self.assertEqual(row["waste_category"], "glass")
            self.assertAlmostEqual(float(row["confidence"]), 0.9750, places=4)
            self.assertEqual(row["capture_source"], "live_camera")

            # 3. Insert linked recycling operation (verifies foreign key relationship)
            op_rec = supabase_client.create_recycling_operation(
                classification_id=unique_test_id,
                processing_pathway="recycling",
                operation_status="completed",
                is_simulated=True
            )
            self.assertIsNotNone(op_rec["id"])

            # 4. Direct cloud SELECT on operations table
            op_fetch = client.table("recycling_operations").select("*").eq("id", op_rec["id"]).execute()
            self.assertEqual(len(op_fetch.data), 1)
            self.assertEqual(op_fetch.data[0]["classification_id"], unique_test_id)

            # 5. Direct verification in PostgreSQL View
            view_res = client.table("view_recent_classifications").select("*").eq("classification_id", unique_test_id).execute()
            self.assertEqual(len(view_res.data), 1, "Test record must be visible through view_recent_classifications")

        finally:
            # 6. Immediate cleanup and verification
            client.table("recycling_operations").delete().eq("classification_id", unique_test_id).execute()
            client.table("waste_classifications").delete().eq("id", unique_test_id).execute()
            verify_del = client.table("waste_classifications").select("id").eq("id", unique_test_id).execute()
            self.assertEqual(len(verify_del.data), 0, "Test classification record must be removed after cleanup")
            print(f"\n[TEST 10 PASSED] Direct Cloud Supabase CRUD lifecycle, FK integrity, and cleanup verified: {unique_test_id}")

    def test_11_sqlite_replica_fallback_integrity(self):
        """[SQLITE FALLBACK INTEGRITY] Verifies that local SQLite replica tables and schema remain intact for offline resilience."""
        conn = get_db_connection()
        cur = conn.cursor()
        test_local_id = str(uuid.uuid4())
        try:
            # Insert into local replica
            cur.execute(
                """
                INSERT INTO waste_classifications (
                    id, waste_category, confidence, model_version, capture_source,
                    classification_status, created_at, metadata
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (test_local_id, "plastic", 0.9123, "mobilenetv2-v1.0", "live_camera", "successful", "2026-10-16T12:00:00", "{}")
            )
            conn.commit()

            # Query local replica
            cur.execute("SELECT waste_category, confidence FROM waste_classifications WHERE id = ?", (test_local_id,))
            row = cur.fetchone()
            self.assertIsNotNone(row)
            self.assertEqual(row["waste_category"], "plastic")
            self.assertAlmostEqual(row["confidence"], 0.9123, places=4)
        finally:
            cur.execute("DELETE FROM waste_classifications WHERE id = ?", (test_local_id,))
            conn.commit()
            conn.close()

        print(f"\n[TEST 11 PASSED] Local SQLite fallback replica integrity and CRUD verified: {test_local_id}")

