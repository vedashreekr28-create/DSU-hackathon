        sql_content = migration_file.read_text(encoding="utf-8")
        
        # Check Tables
        self.assertIn("CREATE TABLE IF NOT EXISTS waste_classifications", sql_content)
        self.assertIn("CREATE TABLE IF NOT EXISTS recycling_operations", sql_content)
